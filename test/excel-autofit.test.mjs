import {test} from "node:test";
 import assert from "node:assert/strict";
 import {readFileSync} from "node:fs";
 import {loadActions,implOf,previewOf} from "./helpers/actions.mjs";
 function fixture(supported=true){const events=[],writes=[];
let runs=0,pendingColumns=false,pendingRows=false;
const track=(object,label)=>new Proxy(object,{set(t,k,v){writes.push(label+"."+String(k));
events.push("write:"+label+"."+String(k));
t[k]=v;
return true;
}});
const state={columnWidth:80,rowHeight:20,wrapText:false,horizontalAlignment:"General",verticalAlignment:"Bottom",font:track({name:"Calibri",size:11,bold:false},"font"),fill:track({color:"#FFFFFF"},"fill"),load(fields){events.push("load-format:"+fields);
},autofitColumns(){events.push("columns");
pendingColumns=true;
},autofitRows(){events.push("rows");
pendingRows=true;
}};
const format=track(state,"format"),range=track({address:"Report!A1:B2",rowCount:2,columnCount:2,values:[["long text",3],["second row",4]],formulas:[["",""],["",""]],numberFormat:[["General"]],format,load(fields){events.push("load-range:"+fields);
}},"range");
const util={okResult:result=>({ok:true,result}),errResult:(code,error)=>({ok:false,code,error}),excelRange:()=>{events.push("range");
return range;
}};
const {A,sandbox}=loadActions({host:"Excel",util,supported:true});
sandbox.Office.context.requirements.isSetSupported=(set,version)=>{events.push("gate:"+set+":"+version);
return version==="1.2"?supported:true;
};
sandbox.Excel.run=async callback=>{runs++;
events.push("run");
return callback({workbook:{tables:{getItem(){throw Error("unexpected table");
}}},sync:async()=>{events.push("sync");
if(pendingColumns){state.columnWidth=144;
pendingColumns=false;
}if(pendingRows){state.rowHeight=42;
pendingRows=false;
}}});
};
return{call:args=>implOf(A,"Excel","format_range")(args),preview:args=>previewOf(A,"Excel","format_range")(args),events,writes,get runs(){return runs;
}};
} test("autofit requires ExcelApi 1.2 before any run or write, including preview",async()=>{for(const sizing of [{autoFitColumns:true},{autoFitRows:true},{autoFit:true},{autoFitColumns:true,autoFitRows:true}])for(const mode of ["call","preview"]){const h=fixture(false),r=await h[mode]({address:"Report!A1:B2",font:"Arial",fill:"#EEEEEE",wrapText:true,...sizing});
assert.equal(r.code,"requirement");
assert.equal(h.runs,0);
assert.deepEqual(h.writes,[]);
assert.deepEqual(h.events,["gate:ExcelApi:1.2"]);
}});
 test("native wrap precedes columns then rows and readback contains actual dimensions",async()=>{const h=fixture(),r=await h.call({address:"Report!A1:B2",autoFitColumns:true,autoFitRows:true,wrapText:true,numberFormat:"#,##0"});
assert.equal(r.ok,true,r.error);
const l=r.result.verification.layout;
assert.equal(l.columnWidth,144);
assert.equal(l.rowHeight,42);
assert.equal(l.wrapText,true);
assert.ok(h.events.indexOf("gate:ExcelApi:1.2")<h.events.indexOf("run"));
assert.ok(h.events.indexOf("write:format.wrapText")<h.events.indexOf("columns"));
assert.ok(h.events.indexOf("columns")<h.events.indexOf("rows"));
assert.ok(h.events.findIndex(e=>e.startsWith("load-format:"))>h.events.indexOf("rows"));
});
 test("preview returns current state separately from requests without autosizing or writes",async()=>{const h=fixture(),r=await h.preview({address:"Report!A1:B2",autoFitColumns:true,autoFitRows:true,wrapText:true,font:"Arial"});
assert.equal(r.ok,true,r.error);
assert.equal(r.result.previewOnly,true);
assert.equal(r.result.layout.columnWidth,80);
assert.equal(r.result.layout.rowHeight,20);
assert.equal(r.result.layout.wrapText,false);
assert.equal(r.result.requested.autoFitColumns,true);
assert.deepEqual(h.writes,[]);
assert.ok(!h.events.includes("columns"));
assert.ok(!h.events.includes("rows"));
});
 test("legacy alias is compatible, both aliases size columns once and false is inert",async()=>{for(const args of [{autoFit:true},{autoFit:true,autoFitColumns:true}]){const h=fixture();
assert.equal((await h.call({address:"Report!A1:B2",...args})).ok,true);
assert.equal(h.events.filter(e=>e==="columns").length,1);
assert.ok(!h.events.includes("rows"));
}const h=fixture(false),r=await h.call({address:"Report!A1:B2",autoFitColumns:false,autoFitRows:false,wrapText:true});
assert.equal(r.ok,true,r.error);
assert.equal(r.result.verification.layout.wrapText,true);
assert.ok(!("columnWidth" in r.result.verification.layout));
assert.ok(!h.events.includes("columns"));
assert.ok(!h.events.includes("rows"));
});
 test("invalid booleans and fixed-sizing conflicts fail before execution and preview",async()=>{for(const args of [{autoFitColumns:"true"},{autoFitColumns:1},{autoFitColumns:true,columnWidth:80},{autoFitRows:true,rowHeight:24}])for(const mode of ["call","preview"]){const h=fixture(),r=await h[mode]({address:"Report!A1:B2",...args});
assert.equal(r.code,"bad_args");
assert.equal(h.runs,0);
assert.deepEqual(h.writes,[]);
}});
 test("bilingual metadata exposes the optional boolean and conditional API requirement",()=>{const meta=JSON.parse(readFileSync(new URL("../server/capabilities.json",import.meta.url))).find(x=>x.name==="format_range");
assert.match(meta.requirement,/autofit.*1\.2/);
for(const lang of ["en","zh"]){const data=JSON.parse(readFileSync(new URL("../i18n/"+lang+".json",import.meta.url)));
let args;
function visit(o){if(!o||typeof o!=="object")return;
if(o.format_range)args=o.format_range.args;
for(const v of Object.values(o))visit(v);
}visit(data);
assert.match(args.autoFitColumns,/boolean/);
assert.match(args.autoFitColumns,/1\.2/);
assert.match(args.autoFit,/autoFitColumns/);
}});
